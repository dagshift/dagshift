"""Reports: console text, Markdown, JSON and SARIF 2.1.0 (GitHub code scanning)."""
from __future__ import annotations

import json
from collections import Counter, defaultdict

from . import __version__
from .engine import MigrationRun
from .findings import Severity
from .rules_catalog import RULES, rule_help, rule_name

_ORDER = {Severity.MANUAL: 0, Severity.WARN: 1, Severity.FIXED: 2, Severity.INFO: 3}
_LABEL = {Severity.MANUAL: "manual", Severity.WARN: "warn", Severity.FIXED: "fixed", Severity.INFO: "info"}


def summary_counts(run: MigrationRun) -> dict[str, int]:
    return {
        "files_scanned": len(run.files),
        "files_changed": len(run.changed),
        "fixed": run.count(Severity.FIXED),
        "manual": run.count(Severity.MANUAL),
        "warn": run.count(Severity.WARN),
        "info": run.count(Severity.INFO),
        "errors": len(run.errors),
    }


def upgrade_line(run: MigrationRun) -> str:
    src = run.kb.source or "unknown"
    how = ""
    if run.detection is not None:
        ev = run.detection.evidence[0] if run.detection.evidence else None
        how = f", detected from {ev.file}:{ev.line}" if ev else ", not detected"
    elif run.kb.source:
        how = ", set explicitly"
    return f"Airflow {src} -> {run.kb.target} (current version{how}; rules verified on Airflow {run.kb.built_from})"


def to_text(run: MigrationRun, verbose: bool = False) -> str:
    c = summary_counts(run)
    lines = [
        f"dagshift {__version__}: {upgrade_line(run)}",
        f"{c['files_scanned']} files scanned, {c['files_changed']} changed | "
        f"{c['fixed']} fixed, {c['manual']} manual, {c['warn']} warn, {c['info']} info"
        + (f", {c['errors']} unparseable" if c["errors"] else ""),
        "",
    ]
    by_file = defaultdict(list)
    for f in run.findings:
        by_file[f.path].append(f)
    for path in sorted(by_file):
        items = sorted(by_file[path], key=lambda f: (f.line, _ORDER[f.severity]))
        shown = [f for f in items if verbose or f.severity in (Severity.MANUAL, Severity.WARN, Severity.FIXED)]
        if not shown:
            continue
        lines.append(path)
        for f in shown:
            lines.append(f"  {f.line:>5}  {_LABEL[f.severity]:<6} {f.rule_id}  {f.message}")
            if verbose and f.recipe and f.severity in (Severity.MANUAL, Severity.WARN):
                for r in f.recipe.splitlines():
                    lines.append(f"{'':>15}-> {r}")
        lines.append("")
    for r in run.errors:
        lines.append(f"{r.path}: {r.error}")
    return "\n".join(lines).rstrip() + "\n"


def to_markdown(run: MigrationRun, title: str | None = None) -> str:
    c = summary_counts(run)
    title = title or f"Airflow {run.kb.source or ''} to {run.kb.target} upgrade report".replace("  ", " ")
    out = [
        f"# {title}",
        "",
        f"{upgrade_line(run)}. Generated by dagshift {__version__}.",
        "",
        "| Files scanned | Files changed | Fixed | Needs you | Warnings | Info |",
        "|---|---|---|---|---|---|",
        f"| {c['files_scanned']} | {c['files_changed']} | {c['fixed']} | {c['manual']} | {c['warn']} | {c['info']} |",
        "",
    ]
    if run.errors:
        out += ["## Files dagshift could not parse", ""]
        out += [f"- `{r.path}`: {r.error}" for r in run.errors]
        out.append("")
    manual = [f for f in run.findings if f.severity in (Severity.MANUAL, Severity.WARN)]
    if manual:
        out += ["## Needs a decision", "",
                f"Each item breaks or changes behaviour on Airflow {run.kb.target} and has no safe automatic "
                "rewrite.", ""]
        for f in sorted(manual, key=lambda f: (_ORDER[f.severity], f.path, f.line)):
            out.append(f"### {_LABEL[f.severity].upper()} {f.rule_id} `{f.path}:{f.line}`")
            out.append("")
            out.append(f.message)
            if f.recipe:
                out += ["", "**What to do**", ""]
                out += _recipe_md(f.recipe)
            out.append("")
    fixed = Counter(f.rule_id for f in run.findings if f.severity == Severity.FIXED)
    if fixed:
        out += ["## Fixed automatically", "", "| Rule | What | Count |", "|---|---|---|"]
        for rid, n in sorted(fixed.items()):
            out.append(f"| {rid} | {rule_help(rid)} | {n} |")
        out.append("")
        out += ["<details><summary>Every automatic change</summary>", ""]
        for f in sorted((f for f in run.findings if f.severity == Severity.FIXED), key=lambda f: (f.path, f.line)):
            out.append(f"- `{f.path}:{f.line}` {f.rule_id}: {f.message}")
        out += ["", "</details>", ""]
    info = [f for f in run.findings if f.severity == Severity.INFO]
    if info:
        out += ["## Good to know before cutover", ""]
        for f in sorted(info, key=lambda f: (f.rule_id, f.path, f.line)):
            line = f"- `{f.path}:{f.line}` {f.rule_id}: {f.message}"
            if f.recipe:
                line += f" {f.recipe}"
            out.append(line)
        out.append("")
    return "\n".join(out)


def _recipe_md(recipe: str) -> list[str]:
    """Plain lines stay prose; runs of 4-space-indented lines become a python code block."""
    out: list[str] = []
    in_code = False
    for line in recipe.splitlines():
        code = line.startswith("    ")
        if code and not in_code:
            out += ["", "```python"]
            in_code = True
        elif not code and in_code:
            out += ["```", ""]
            in_code = False
        out.append(line[4:] if code else line)
    if in_code:
        out.append("```")
    return out


def to_json(run: MigrationRun) -> str:
    return json.dumps({
        "dagshift": __version__,
        "source": run.kb.source,
        "detection": run.detection.to_dict() if run.detection else None,
        "target": run.kb.target,
        "verified_against": run.kb.built_from,
        "summary": summary_counts(run),
        "files": [
            {"path": r.path, "kind": r.kind, "changed": r.changed, "templated": r.templated, "error": r.error,
             "findings": [f.to_dict() for f in r.findings]}
            for r in run.files
        ],
        "project_findings": [f.to_dict() for f in run.project_findings],
    }, indent=2)


def to_sarif(run: MigrationRun) -> str:
    level = {Severity.MANUAL: "error", Severity.WARN: "warning", Severity.INFO: "note", Severity.FIXED: "note"}
    used = sorted({f.rule_id for f in run.findings})
    rules = [{"id": rid, "name": rule_name(rid), "shortDescription": {"text": rule_help(rid)}}
             for rid in used if rid in RULES]
    results = []
    for f in run.findings:
        if f.severity == Severity.FIXED:
            continue  # fixes are applied, not open issues
        msg = f.message + (f"\n{f.recipe}" if f.recipe else "")
        results.append({
            "ruleId": f.rule_id,
            "level": level[f.severity],
            "message": {"text": msg},
            "locations": [{"physicalLocation": {"artifactLocation": {"uri": f.path},
                                                "region": {"startLine": max(1, f.line)}}}],
        })
    return json.dumps({
        "version": "2.1.0",
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "runs": [{"tool": {"driver": {"name": "dagshift", "version": __version__, "rules": rules}},
                  "results": results}],
    }, indent=2)
